"""frames — the authored surface inventory the template generator expands.

Data only: no expansion, no validation, no I/O. Each frame is a request with
``{slot}`` holes; ``templates.py`` fills them, and ``bands.py`` decides whether the
result lands in the band the frame claims. A frame that fails that check is a
bug in this table and is reported as dropped, not silently kept.

Three registers are mixed on purpose, because 01 §6 names phrasing shift as a
failure mode: the corpus holds terse imperatives, chatty lowercase run-ons with
typos, and multi-clause sentences. Uniform rhythm is the thing to avoid — if
every request starts with a verb and ends with a full stop, the model learns the
rhythm instead of the intent.

Constraints carried from ``tests/data/utterances_v2_NOTES.md``:

* t2 frames must contain NO op-signature vocabulary at all (that is what veiled
  means here), and the generator asserts it;
* t3 frames must cue the label *and* the rival, since a boundary row only exists
  if the other reading is cued too — the label is the semantically correct one;
* nothing is self-referential ("run the grep op"), and no frame names an op.
"""
