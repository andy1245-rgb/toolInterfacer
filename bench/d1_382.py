#!/usr/bin/env python3
"""d1_382 — the row-wise 382 figure and its template-held-out companion, both measured here.

`spec/1.0-spec.md` quotes "d1-3B today: 91.4% tool routing" from the imported
benchmark. That is a real row-wise number, but it is a different task from this
repo's 8 file/web ops — `tests/data/routing_382.json` is 382 rows over 18
smart-home classes (`timer_create`, `thermostat_set`, `shoppinglist_add`, …), and
the two label sets are disjoint. The benchmark's own results file also records a
per-family accuracy; only the row-wise half was ever published here.

Both halves are reconstructible from the rows in this tree, so this script
measures both against whatever d1-3B the endpoint is actually serving, and writes
the per-row data so a reader can recompute either number without the model.

    python3 bench/d1_382.py --out bench/results/d1-382-2026-11-04.json
    python3 bench/d1_382.py --recompute bench/results/d1-382-2026-11-04.json

Grouping
--------
Templates, not topics. Each row was generated by substituting slots into a
registry template, so `eval_harness.load_382(grouping="template")` recovers the
generating template from the literal prefix/suffix the row still carries: 110
groups (109 templates + one per-label bucket for the template-less `__none__`
rows). The `family` column shipped with the file has only 7 values and they are
*topics* (`timers`, `climate`, `shopping`, …): holding out `timers` removes every
timer phrasing and the `timer_create` class along with them, so a topic-held-out
score is structurally 0 and measures nothing. `--grouping topic` still runs, for
a reader who wants to see that collapse rather than take it on trust.

What the two numbers are, and what they are not
-----------------------------------------------
d1-3B is frozen — nothing in this run fits on these rows, so the point estimate
is the same under either grouping and saying otherwise would be an invention.
What the grouping changes is the interval: rows of one template are one
observation, so the honest interval resamples whole templates (cluster bootstrap,
the same `eval_harness.cluster_bootstrap_ci` the other lanes use) and is wider
than the Wilson interval the row-wise figure is published with. The artifact
carries both intervals, the width ratio between them, and the per-template
accuracy distribution, which is the family-level view a single row-wise number
hides.
"""
from __future__ import annotations

import argparse
import json
import statistics
import sys
import time
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "service"))
sys.path.insert(0, str(Path(__file__).resolve().parent))

import eval_harness as H  # noqa: E402
from ti_bench import arms as arms_mod  # noqa: E402
from ti_bench import guard as guard_mod  # noqa: E402
from ti_bench.prompts import INSTRUCTIONS  # noqa: E402
from ti_bench.stats import percentile, wilson_ci  # noqa: E402

SCHEMA = "ti-bench/d1-382/1"
ARM = "d1"
GROUPING_UNIT = {
    "template": "reconstructed generating template (bench/eval_harness.py::load_382)",
    "topic": "shipped `family` column — 7 topics, not templates",
    "row": "row",
}
DEFAULT_OUT = ROOT / "bench/results/d1-382-2026-11-04.json"


def _rel(path: Path | str) -> str:
    """Repo-relative when inside the repo, so the artifact stays portable."""
    try:
        return str(Path(path).resolve().relative_to(ROOT))
    except ValueError:
        return str(path)


def criteria_for(labels) -> dict[str, str]:
    """The ballot: one criterion per class, described by its own name.

    The same 18-option ballot `bench/classical_baseline.py` scores the 382 board
    with, `__none__` included — it is a real class in this file, and a lane that
    withholds it from d1 while handing it to the linear model would not be
    comparing two voters on one board.
    """
    return {label: label for label in labels}


def measure(backend, ds: H.Dataset, every: int = 25, stream=None) -> list[dict]:
    """One call per row; a failed row is recorded, never allowed to lose the rest."""
    stream = stream if stream is not None else sys.stderr
    criteria = criteria_for(ds.labels)
    per_row = []
    for idx, example in enumerate(ds.examples):
        t0 = time.perf_counter()
        try:
            answer = backend.choice(example.text, INSTRUCTIONS, criteria)
        except Exception as e:  # noqa: BLE001 — one transport failure is one row
            per_row.append({"idx": idx, "utterance": example.text,
                            "expected": example.label, "predicted": None,
                            "correct": False, "confidence": None,
                            "latency_ms": round((time.perf_counter() - t0) * 1000, 3),
                            "group": example.group, "error": str(e) or type(e).__name__})
            continue
        ms = (time.perf_counter() - t0) * 1000
        predicted = getattr(answer, "choice", None)
        per_row.append({"idx": idx, "utterance": example.text,
                        "expected": example.label, "predicted": predicted,
                        "correct": predicted == example.label,
                        "confidence": round(float(getattr(answer, "confidence", 0.0) or 0.0), 6),
                        "latency_ms": round(ms, 3), "group": example.group,
                        "error": None if predicted else "empty choice"})
        if every and (idx + 1) % every == 0:
            done = per_row[-every:]
            print(f"  {idx + 1}/{len(ds.examples)} "
                  f"acc={sum(r['correct'] for r in per_row) / len(per_row):.3f} "
                  f"p50={percentile([r['latency_ms'] for r in done], 0.5):.0f}ms",
                  file=stream, flush=True)
    return per_row


def _per_group(per_row: list[dict]) -> dict:
    buckets: dict[str, list[bool]] = {}
    for row in per_row:
        buckets.setdefault(row["group"], []).append(bool(row["correct"]))
    accs = {g: sum(v) / len(v) for g, v in sorted(buckets.items())}
    return {
        "n_groups": len(buckets),
        "rows_per_group": {"min": min(len(v) for v in buckets.values()),
                           "median": statistics.median(len(v) for v in buckets.values()),
                           "max": max(len(v) for v in buckets.values())},
        "singleton_groups": sum(1 for v in buckets.values() if len(v) == 1),
        "accuracy": {"macro_mean_over_groups": round(statistics.fmean(accs.values()), 4),
                     "median": round(statistics.median(accs.values()), 4),
                     "min": round(min(accs.values()), 4),
                     "max": round(max(accs.values()), 4),
                     "groups_at_1.0": sum(1 for a in accs.values() if a == 1.0),
                     "groups_at_0.0": sum(1 for a in accs.values() if a == 0.0)},
        "per_group": {g: {"n": len(buckets[g]), "correct": sum(buckets[g]),
                          "accuracy": round(accs[g], 4)} for g in accs},
    }


def held_out_key(grouping: str) -> str:
    """The aggregate's key: `template_held_out` for the default grouping."""
    return f"{grouping}_held_out"


def aggregate(per_row: list[dict], n_boot: int = H.DEFAULT_BOOT,
              boot_seed: int = 0, grouping: str = "template") -> dict:
    """Both aggregates from the same outcomes: row-wise, and with groups as the unit."""
    n = len(per_row)
    correct = sum(1 for r in per_row if r["correct"])
    outcomes = [1.0 if r["correct"] else 0.0 for r in per_row]
    groups = [r["group"] for r in per_row]
    lo_w, hi_w = wilson_ci(correct, n)
    lo_c, hi_c = H.cluster_bootstrap_ci(outcomes, groups, n_boot=n_boot, seed=boot_seed)
    per_group = _per_group(per_row)
    by_label: dict[str, dict[str, int]] = {}
    for row in per_row:
        slot = by_label.setdefault(row["expected"], {"n": 0, "correct": 0})
        slot["n"] += 1
        slot["correct"] += int(row["correct"])
    latencies = [r["latency_ms"] for r in per_row if r["error"] in (None, "empty choice")]
    confs = [r["confidence"] for r in per_row if r["confidence"] is not None]

    return {
        "row_wise": {
            "accuracy": round(correct / n, 4) if n else 0.0,
            "correct": correct, "n": n, "unit": "row",
            "ci": {"method": "wilson", "level": H.CI_LEVEL,
                   "lo": round(lo_w, 4), "hi": round(hi_w, 4)},
        },
        held_out_key(grouping): {
            "accuracy": round(correct / n, 4) if n else 0.0,
            "n_rows": n, "n_groups": per_group["n_groups"],
            "grouping": grouping, "unit": GROUPING_UNIT.get(grouping, grouping),
            "ci": {"method": "cluster_bootstrap", "level": H.CI_LEVEL,
                   "n_boot": n_boot, "seed": boot_seed,
                   "lo": round(lo_c, 4), "hi": round(hi_c, 4)},
            "note": ("d1-3B is frozen: nothing fits on these rows, so the point "
                     "estimate is identical to row_wise by construction. The "
                     "grouping changes the interval, not the estimate — the "
                     "cluster interval is the one a held-out claim may make."),
        },
        "interval_width_ratio_cluster_over_wilson": round((hi_c - lo_c) / (hi_w - lo_w), 3)
        if hi_w > lo_w else None,
        "per_group": per_group,
        "accuracy_by_label": {k: {"n": v["n"], "accuracy": round(v["correct"] / v["n"], 4)}
                              for k, v in sorted(by_label.items())},
        "malformed_responses": sum(1 for r in per_row if r["error"] == "empty choice"),
        "errors": sum(1 for r in per_row if r["error"] not in (None, "empty choice")),
        "latency_ms": {"p50": round(percentile(latencies, 0.5), 1),
                       "p90": round(percentile(latencies, 0.9), 1),
                       "p95": round(percentile(latencies, 0.95), 1),
                       "p99": round(percentile(latencies, 0.99), 1),
                       "mean": round(statistics.fmean(latencies), 1) if latencies else 0.0},
        "confidence": {"p50": round(statistics.median(confs), 4) if confs else None,
                       "mean": round(statistics.fmean(confs), 4) if confs else None},
    }


def _served_identity(props: dict) -> dict:
    """The /props fields worth keeping as the run's own identity record."""
    from model_guard import served_model

    served = served_model(props)
    return {k: v for k, v in served.items() if v not in (None, "")}


def report(per_row: list[dict], *, grouping: str, guard_block: dict, props: dict,
           base_url: str, n_boot: int, boot_seed: int, argv: list[str]) -> dict:
    ds = H.load_382(grouping=grouping)
    agg = aggregate(per_row, n_boot=n_boot, boot_seed=boot_seed, grouping=grouping)
    topic = H.load_382(grouping="topic")
    return {
        "schema": SCHEMA,
        "generated": time.strftime("%Y-%m-%dT%H:%M:%S%z"),
        "task_context": {
            "set": "tests/data/routing_382.json",
            "rows": len(per_row),
            "classes": len(ds.labels),
            "labels": list(ds.labels),
            "note": ("the imported benchmark's 18 smart-home classes; disjoint from "
                     "this repo's 8 file/web ops, so no figure here is comparable "
                     "with a v1/v2 number"),
        },
        "protocol": {
            "question": INSTRUCTIONS,
            "ballot": "one criterion per class, described by its own name (__none__ included)",
            "backend": "d1_systemone — POST /v1/systemone, state = the utterance",
            "base_url": base_url,
            "grouping": grouping,
            "grouping_unit": GROUPING_UNIT.get(grouping, grouping),
            "n_groups": agg[held_out_key(grouping)]["n_groups"],
            "bootstrap": {"n_boot": n_boot, "seed": boot_seed, "cluster": "template"},
            "warmup_calls_discarded": 0,
            "topic_families_present": len(set(topic.groups)),
            "topic_grouping_note": ("the shipped `family` column is 7 topics, not "
                                    "templates; excluded from the headline figure "
                                    "because holding a topic out deletes whole label "
                                    "classes (bench/d1_382.py docstring)"),
            "argv": argv,
        },
        "model_assertion": guard_block,
        "server_props": _served_identity(props),
        "row_wise": agg["row_wise"],
        held_out_key(grouping): agg[held_out_key(grouping)],
        "interval_width_ratio_cluster_over_wilson":
            agg["interval_width_ratio_cluster_over_wilson"],
        "per_group": agg["per_group"],
        "accuracy_by_label": agg["accuracy_by_label"],
        "malformed_responses": agg["malformed_responses"],
        "errors": agg["errors"],
        "latency_ms": agg["latency_ms"],
        "confidence": agg["confidence"],
        "per_row": per_row,
    }


def recompute(path: Path, n_boot: int, boot_seed: int) -> int:
    """Re-derive both aggregates from a written artifact: no model, no traffic."""
    payload = json.loads(path.read_text())
    per_row = payload["per_row"]
    grouping = str((payload.get("protocol") or {}).get("grouping") or "template")
    agg = aggregate(per_row, n_boot=n_boot, boot_seed=boot_seed, grouping=grouping)
    key = held_out_key(grouping)
    _print_summary(agg, key, source=str(path))
    recorded = (payload.get("row_wise", {}).get("accuracy"),
                payload.get(key, {}).get("accuracy"))
    fresh = (agg["row_wise"]["accuracy"], agg[key]["accuracy"])
    if recorded != fresh:
        print(f"  MISMATCH: recorded {recorded}, recomputed {fresh}", file=sys.stderr)
        return 1
    return 0


def _print_summary(agg: dict, key: str, source: str = "") -> None:
    """Both numbers, their intervals, n and the grouping unit — one format, both paths."""
    rw, ho = agg["row_wise"], agg[key]
    if source:
        print(f"{source}: n={rw['n']} groups={ho['n_groups']}")
    print(f"  row-wise           {rw['accuracy'] * 100:.2f}% "
          f"wilson 95% [{rw['ci']['lo'] * 100:.2f}, {rw['ci']['hi'] * 100:.2f}]  n={rw['n']}")
    print(f"  {ho['grouping'] + '-held-out':<18} {ho['accuracy'] * 100:.2f}% "
          f"cluster 95% [{ho['ci']['lo'] * 100:.2f}, {ho['ci']['hi'] * 100:.2f}]  "
          f"n={ho['n_rows']} rows in {ho['n_groups']} {ho['grouping']} groups")
    print(f"  macro over groups  "
          f"{agg['per_group']['accuracy']['macro_mean_over_groups'] * 100:.2f}%  "
          f"p50={agg['latency_ms']['p50']}ms")


def parse_args(argv: list[str] | None = None) -> argparse.Namespace:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--arm", default=ARM, help=f"arm from bench/arms.json (default {ARM})")
    ap.add_argument("--grouping", default="template", choices=("template", "topic", "row"))
    ap.add_argument("--out", default=str(DEFAULT_OUT))
    ap.add_argument("--base-url", default="", help="repoint the arm's endpoint")
    ap.add_argument("--expect-model", default="", help="gguf basename the server must serve")
    ap.add_argument("--allow-unasserted-model", action="store_true")
    ap.add_argument("--limit", type=int, default=0, help="first N rows only (smoke test)")
    ap.add_argument("--n-boot", type=int, default=H.DEFAULT_BOOT)
    ap.add_argument("--boot-seed", type=int, default=0)
    ap.add_argument("--force", action="store_true", help="overwrite an existing --out")
    ap.add_argument("--recompute", default="", help="re-derive both numbers from an artifact")
    return ap.parse_args(argv)


def main(argv: list[str] | None = None) -> int:
    args = parse_args(argv)
    if args.recompute:
        return recompute(Path(args.recompute), args.n_boot, args.boot_seed)

    out = Path(args.out)
    if out.exists() and not args.force:
        print(f"refused: {_rel(out)} exists (pass --force to replace it)", file=sys.stderr)
        return 1

    arm = arms_mod.get_arm(args.arm)
    arms_mod.apply(arm, args.base_url)
    try:
        guard_block = guard_mod.preflight(arm, args.expect_model, args.allow_unasserted_model)
    except guard_mod.GuardError as e:
        print(f"ABORT: {e}", file=sys.stderr)
        return 3
    base_url = str(arms_mod.conf_value(arm.endpoint) or "") if arm.endpoint else ""
    with urllib.request.urlopen(base_url.rstrip("/") + "/props", timeout=10) as resp:
        props = json.loads(resp.read())
    backend = arms_mod.build(arm)

    ds = H.load_382(grouping=args.grouping)
    examples = ds.examples[: args.limit] if args.limit else ds.examples
    ds_subset = H.Dataset(name=ds.name, examples=examples, labels=ds.labels, note=ds.note)
    print(f"{arm.name} on {len(examples)} rows of the 382, grouping={args.grouping}, "
          f"serving {guard_block.get('served_basename', '?')}", flush=True)
    per_row = measure(backend, ds_subset)

    payload = report(per_row, grouping=args.grouping, guard_block=guard_block, props=props,
                     base_url=base_url, n_boot=args.n_boot, boot_seed=args.boot_seed,
                     argv=sys.argv[1:])
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(json.dumps(payload, indent=1) + "\n")

    rw, ho = payload["row_wise"], payload[held_out_key(args.grouping)]
    print(f"model assertion: "
          f"{'OK — serving ' + str(guard_block.get('served_basename', '?')) if guard_block.get('checked') else 'NOT ASSERTED'}")
    _print_summary({"row_wise": rw, held_out_key(args.grouping): ho,
                    "per_group": payload["per_group"],
                    "latency_ms": payload["latency_ms"]}, held_out_key(args.grouping))
    print(f"wrote {_rel(out)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
